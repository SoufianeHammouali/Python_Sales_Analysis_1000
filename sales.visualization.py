import pandas as pd
import matplotlib.pyplot as plt
df = pd.read_csv("Data/clean_sales_data.csv")
print("Dataset Shape:",df.shape)
Revenue_by_Category=df.groupby("Category")["Net_Revenue_MAD"].sum().sort_values(ascending=False)
plt.figure(figsize=(10,6))
plt.barh(Revenue_by_Category.index,Revenue_by_Category.values,color="#16A34A")
plt.title("Revenue by Product Category 2025",fontsize=15)
plt.xlabel("Net Revenue (MAD)")
plt.ylabel("Product Category")
plt.grid(axis="x",  linestyle="--", alpha=0.3)
plt.tight_layout()
plt.savefig("Charts/revenue_by_category.png", dpi=300)
plt.show()
# Profit by Category
profit_by_category = (
    df.groupby("Category")["Profit_MAD"]
    .sum()
    .sort_values(ascending=True))
plt.figure(figsize=(10, 6))

plt.barh(profit_by_category.index,
    profit_by_category.values,
    color="#16A34A")
plt.title("Profit by Product Category — 2025", fontsize=15)
plt.xlabel("Total Profit (MAD)")
plt.ylabel("Product Category")
plt.grid(axis="x", linestyle="--", alpha=0.3)
plt.tight_layout()
plt.savefig("Charts/profit_by_category.png", dpi=300)
plt.show()
# Monthly Revenue Trend
df["Date"] = pd.to_datetime(df["Date"])
df["Month"] = df["Date"].dt.to_period("M")

monthly_revenue = (df.groupby("Month")["Net_Revenue_MAD"].sum().sort_index())
plt.figure(figsize=(12,6))
plt.plot(monthly_revenue.index.astype(str),monthly_revenue.values,marker="o",linewidth=2.5,color="#2563EB")
plt.title("Monthly Revenue Trend — 2025", fontsize=15)
plt.xlabel("Month")
plt.ylabel("Net Revenue (MAD)")
plt.xticks(rotation=45)
plt.grid(linestyle="--", alpha=0.3)
plt.tight_layout()
plt.savefig("Charts/monthly_revenue_trend.png", dpi=300)
plt.show()
revenue_by_channel=(df.groupby("Sales_Channel")["Net_Revenue_MAD"].sum().sort_values(ascending=False))
plt.figure(figsize=(9,6))
bars=plt.bar(revenue_by_channel.index,revenue_by_channel.values,color=["#2563EB", "#0D9488", "#F59E0B"])
plt.title("Revenue by Sales Channel — 2025", fontsize=15)
plt.xlabel("Sales Channel")
plt.ylabel("Net Revenue(MAD)")
plt.bar_label(bars,labels=[f"{v / 1_000_000:.2f}M" for v in revenue_by_channel.values],padding=4)
plt.grid(axis="y",linestyle="--",alpha=0.3)
plt.gca().set_axisbelow(True)
plt.tight_layout()
plt.savefig("Charts/revenue_by_channel.png",dpi=300)
plt.show()
