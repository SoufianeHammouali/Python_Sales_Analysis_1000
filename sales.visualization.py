plt.grid(axis="y", linestyle="--", alpha=0.3)
plt.gca().set_axisbelow(True)
plt.tight_layout()
plt.savefig("Charts/revenue_by_customer_segment.png", dpi=300)
plt.show()
top_products=(df.groupby("Product")["Net_Revenue_MAD"].sum().sort_values(ascending=False).head(10).sort_values(ascending=True))
plt.figure(figsize=(11,7))
bars=plt.barh(top_products.index,top_products.values,color="#2563EB")
plt.title("Top 10 Products by Revenue — 2025", fontsize=15)
plt.xlabel("Net Revenue(MAD)")
plt.ylabel("Product")
plt.bar_label(bars,labels=[f"{v / 1000:.0f}K" for v in top_products.values],padding=4)
plt.xlim(0,top_products.max()*1.15)
plt.grid(axis="x",linestyle="--",alpha=0.3)
plt.gca().set_axisbelow(True)
plt.tight_layout()
plt.savefig("Charts/top_10_products_revenue.png", dpi=300)
plt.show()
# Profit Margin by Category
category_profitability = (df.groupby("Category").agg( Revenue=("Net_Revenue_MAD", "sum"), Profit=("Profit_MAD", "sum") ))
category_profitability["Profit_Margin"] = (category_profitability["Profit"]/ category_profitability["Revenue"] * 100)
margin_by_category = (category_profitability["Profit_Margin"].sort_values(ascending=True))
plt.figure(figsize=(10, 6))
bars = plt.barh(margin_by_category.index,margin_by_category.values,color="#0D9488")
plt.title("Profit Margin by Category — 2025", fontsize=15)
plt.xlabel("Profit Margin (%)")
plt.ylabel("Product Category")
plt.bar_label(bars,labels=[f"{v:.2f}%" for v in margin_by_category.values],padding=4)
plt.xlim(0, margin_by_category.max() * 1.15)
plt.grid(axis="x", linestyle="--", alpha=0.3)
plt.gca().set_axisbelow(True)
plt.tight_layout()
plt.savefig("Charts/profit_margin_by_category.png", dpi=300)
plt.show()
revenue_by_city=(df[df["City"]!="Unknown"].groupby("City")["Net_Revenue_MAD"].sum().sort_values(ascending=False).head(8).sort_values(ascending=True))
