import pandas as pd
df = pd.read_excel("Data/Data_Analysis_Practice_Sales_1000.xlsx")
print("Dataset Shape:", df.shape)
print(df.head())
print("Missing value:")
print(df.isnull().sum())
print("Rows With Missing Value")
print(df[df.isnull().any(axis=1)].to_string(index=False))
print("Duplicate rows:", df.duplicated().sum())
print("duplicate Order IDs:",df["Order_ID"].duplicated().sum())
df= df.drop_duplicates()
print("Rows after ckeaning:",len(df))
print("Reamining duplicates:",df.duplicated().sum())
df["Customer_ID"] = df["Customer_ID"].fillna("Unknown")
df["City"] = df["City"].fillna("Unknown")

print("Missing values after cleaning:")
print(df.isnull().sum())
print("Invalid Quantities:", (df["Quantity"] <= 0).sum())
print("Invalid Revenue:", (df["Net_Revenue_MAD"] < 0).sum())
print("Profit calculation errors:",((df["Net_Revenue_MAD"] - df["Total_Cost_MAD"] - df["Profit_MAD"]).abs()>0.01).sum())
df["Date"]=pd.to_datetime(df["Date"],errors="coerce")
print("Invalid Dates:",df["Date"].isnull().sum())
print("First Date:",df["Date"].min())
print("Last Date:",df["Date"].max())
print("Minimum Discount:", df["Discount"].min())
print("Maximum Discount:", df["Discount"].max())
print("Negative Discounts:", (df["Discount"] < 0).sum())
print("Total Rows:",len(df))
print("Unique Order IDs:",df["Order_ID"].nunique())
print("Duplicate Order IDs:",df["Order_ID"].duplicated().sum())
df.to_csv("Data/clean_sales_data.csv", index=False)
print("clean dataset exported successfully!")